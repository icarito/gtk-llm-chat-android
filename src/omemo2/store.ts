// Almacenamiento clave/valor de strings (JSON). Misma forma que expo-secure-store,
// AsyncStorage o una tabla SQLite de dos columnas, para respaldarlo después.
export interface OmemoStore {
  get(key: string): Promise<string | null>;
  set(key: string, value: string): Promise<void>;
  remove(key: string): Promise<void>;
}

export class MemoryStore implements OmemoStore {
  readonly data = new Map<string, string>();
  async get(key: string) {
    return this.data.get(key) ?? null;
  }
  async set(key: string, value: string) {
    this.data.set(key, value);
  }
  async remove(key: string) {
    this.data.delete(key);
  }
}
